"""End-to-end run: load, clean, build examples, cross-validate, fit, export.

    python -m bde.train --raw path/to/extracted/nasa       # from the .mat files
    python -m bde.train                                    # from the committed cycle table

Writes data/processed/nasa_cycles.csv.gz, reports/metrics.json,
artifacts/model.joblib and the explorer's ../battery-explorer/data/model.js
(a script that sets window.BDE_DATA, so the page also works opened from disk).
"""
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np
import pandas as pd

from . import evaluate, export, models
from .clean import segment
from .features import FEATURES, build_anchors, build_examples

ROOT = Path(__file__).resolve().parents[1]
CYCLES = ROOT / "data" / "processed" / "nasa_cycles.csv.gz"


def importance(fc: models.QuantileForecaster, ex: pd.DataFrame, n: int = 4000, seed: int = 0) -> list[dict]:
    """Permutation importance of the median model: rise in MAE (Ah) when a feature is shuffled."""
    rng = np.random.default_rng(seed)
    s = ex.sample(min(n, len(ex)), random_state=seed)
    m = fc.models[0.5]
    mae = lambda X: float(np.mean(np.abs(s["c_now"] * (m.predict(X[FEATURES]) - s["y_rel"]))))
    base, out = mae(s), []
    for f in FEATURES:
        X = s.copy()
        X[f] = rng.permutation(X[f].to_numpy())
        out.append({"feature": f, "mae_increase_ah": round(mae(X) - base, 5)})
    return sorted(out, key=lambda d: -d["mae_increase_ah"])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw", help="directory holding the extracted NASA B00xx.mat files")
    ap.add_argument("--cycles", default=str(CYCLES), help="cycle table to use when --raw is not given")
    ap.add_argument("--out", default=str(ROOT.parent / "battery-explorer" / "data" / "model.js"))
    ap.add_argument("--reports", default=str(ROOT / "reports"))
    ap.add_argument("--max-iter", type=int, default=300)
    a = ap.parse_args(argv)
    t0 = time.time()

    if a.raw:
        from .nasa import load_all
        df = load_all(a.raw)
        CYCLES.parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(CYCLES, index=False, float_format="%.6g")
        print(f"loaded {df['cell'].nunique()} cells, {len(df)} discharges -> {CYCLES.relative_to(ROOT)}")
    else:
        df = pd.read_csv(a.cycles)

    seg = segment(df)
    anchors = build_anchors(seg)
    ex = build_examples(seg, anchors)
    print(f"{seg['usable'].sum()} usable discharges, {len(anchors)} anchors, {len(ex)} examples from {ex['cell'].nunique()} cells")

    print("leave-one-cell-out cross-validation")
    oof, grid = evaluate.cross_validate(ex, anchors, a.max_iter)
    met = evaluate.metrics(oof)

    print("fitting final model on all cells")
    final = models.QuantileForecaster(a.max_iter).fit(ex)
    met["importance"] = importance(final, ex)
    met["widen_rel"] = {str(k): round(v, 5) for k, v in evaluate.widen(oof[["cell", "h", "score"]]).items()}

    rep = Path(a.reports)
    rep.mkdir(parents=True, exist_ok=True)
    (rep / "metrics.json").write_text(json.dumps(met, indent=1))
    try:
        import joblib
        (ROOT / "artifacts").mkdir(exist_ok=True)
        joblib.dump({"model": final, "widen_rel": met["widen_rel"], "features": FEATURES}, ROOT / "artifacts" / "model.joblib")
    except ImportError:
        pass

    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(export.explorer_payload(seg, anchors, grid, met), separators=(",", ":"))
    out.write_text("// Generated by battery-model/bde/train.py. Do not edit by hand.\nwindow.BDE_DATA = " + payload + ";\n")
    print(f"wrote {out} ({out.stat().st_size / 1e3:.0f} kB) in {time.time() - t0:.0f} s")

    m = met["mae_ah_cell_avg"]
    print("\nMAE (Ah), cell-averaged: " + ", ".join(f"{k} {v:.4f}" for k, v in m.items()))
    print(f"80% band coverage: raw {met['coverage_raw']:.2f}, calibrated {met['coverage']:.2f}")
    return met


if __name__ == "__main__":
    main()
